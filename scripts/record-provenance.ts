/** Write a complete application snapshot into `destDir` without touching `.git`. */
function writeSource(destDir: string, behavior: string, isHead: boolean): void {
  fs.mkdirSync(destDir, { recursive: true });
  // Clear only non-.git entries so an existing git repository is preserved.
  for (const entry of fs.readdirSync(destDir, { withFileTypes: true })) {
    if (entry.name === ".git") {
      continue;
    }
    fs.rmSync(path.join(destDir, entry.name), { recursive: true, force: true });
  }
  fs.copyFileSync(path.join(FIXTURE_SRC, "types.ts"), path.join(destDir, "types.ts"));
  fs.copyFileSync(path.join(FIXTURE_SRC, "audit.ts"), path.join(destDir, "audit.ts"));
  fs.writeFileSync(
    path.join(destDir, "app.ts"),
    isHead ? fs.readFileSync(path.join(FIXTURE_SRC, "app.ts"), "utf8") : stubAppText(),
    "utf8"
  );
  fs.writeFileSync(path.join(destDir, "behavior.ts"), behaviorText(behavior), "utf8");
}

function treeDigest(repo: string): string {
  const walk = (dir: string): string[] => {
    let out: string[] = [];
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        out = out.concat(walk(full));
      } else {
        out.push(path.relative(repo, full));
      }
    }
    return out;
  };
  const files = walk(repo).sort();
  const h = crypto.createHash("sha256");
  for (const f of files) {
    h.update(f);
    h.update("\0");
    h.update(fs.readFileSync(path.join(repo, f), "utf8"));
    h.update("\0");
  }
  return h.digest("hex");
}

function main(): void {
  fs.rmSync(WORK, { recursive: true, force: true });
  fs.mkdirSync(WORK, { recursive: true });

  const provenance: Record<string, any> = {};

  for (const c of CANDIDATES) {
    const repo = path.join(WORK, c.id);
    fs.mkdirSync(repo, { recursive: true });
    git(repo, ["init", "-q", "-b", "main"]);
    initIdentity(repo);

    const manifest = JSON.parse(
      fs.readFileSync(path.join(CANDIDATES_DIR, c.id, "MANIFEST.json"), "utf8")
    );
    const headBehavior = manifest.behavior;

    // --- Base commit (deny-all stub, base behavior) ---
    writeSource(repo, BASE_BEHAVIOR[c.base], false);
    git(repo, ["add", "-A"]);
    git(repo, ["commit", "-q", "--allow-empty", "-m", `base: ${c.base} (deny-all stub)`]);
    const baseCommit = git(repo, ["rev-parse", "HEAD"]);
    const baseTree = git(repo, ["rev-parse", "HEAD^{tree}"]);
    const baseTreeDigest = treeDigest(repo);

    // --- Head commit (full candidate implementation, head behavior) ---
    writeSource(repo, headBehavior, true);
    git(repo, ["add", "-A"]);
    git(repo, ["commit", "-q", "--allow-empty", "-m", `head: ${c.head} (${c.id})`]);
    const headCommit = git(repo, ["rev-parse", "HEAD"]);
    const headTree = git(repo, ["rev-parse", "HEAD^{tree}"]);
    const headTreeDigest = treeDigest(repo);

    const diffStat = git(repo, ["diff", "--stat", baseCommit, headCommit]);
    const diffFull = git(repo, ["diff", baseCommit, headCommit]);

    provenance[c.id] = {
      candidate: c.id,
      snapshotPair: `${c.base}@${baseCommit.slice(0, 12)} -> ${c.head}@${headCommit.slice(0, 12)}`,
      base: { id: c.base, commit: baseCommit, tree: baseTree, behavior: BASE_BEHAVIOR[c.base] },
      head: { id: c.head, commit: headCommit, tree: headTree, behavior: headBehavior },
      baseTreeDigest,
      headTreeDigest,
      diffStat,
      diffFull,
      expectedCriteria: manifest.expectedCriteria,
      sanitized: true,
      files: git(repo, ["ls-tree", "-r", "--name-only", headCommit]).split("\n").filter(Boolean),
    };
    console.log(
      `  ${c.id}: base ${baseCommit.slice(0, 12)} tree ${baseTree.slice(0, 12)} | head ${headCommit.slice(0, 12)} tree ${headTree.slice(0, 12)}`
    );
  }

  fs.writeFileSync(
    path.join(CANDIDATES_DIR, "provenance.json"),
    JSON.stringify(provenance, null, 2) + "\n",
    "utf8"
  );
  console.log("Wrote candidates/provenance.json");
}

main();
