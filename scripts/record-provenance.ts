/**
 * Record WP1 candidate snapshot provenance (disposable sanitized git repos).
 *
 * For each S1 candidate, creates a throwaway git repository under
 * .candidates-work/<id>/ containing ONLY the selected application base/head
 * pair (no parent experiment checkout, no sibling candidates, no oracle files).
 *
 * Base commit: a secure-by-default deny-all stub (app before this feature).
 * Head commit: the full candidate implementation (behavior from the candidate
 * snapshot's behavior.ts).
 *
 * Records commit/tree identities and the base-to-head diff for reproducibility.
 *
 * Licensed under Apache 2.0. See LICENSE.
 */

import * as crypto from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const SCRIPTS_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(SCRIPTS_DIR, "..");
const WORK = path.join(ROOT, ".candidates-work");
const CANDIDATES_DIR = path.join(ROOT, "candidates");
const FIXTURE_SRC = path.join(ROOT, "fixture", "src");

interface CandidateMeta {
  id: string;
  base: string;
  head: string;
}

const CANDIDATES: CandidateMeta[] = [
  { id: "S1-C1", base: "B0", head: "H1" },
  { id: "S1-C2", base: "B0", head: "H2" },
  { id: "S1-C3", base: "B0", head: "H3" },
  { id: "S1-C4", base: "B1", head: "H4" },
];

// Base behaviors: B0 = all correct; B1 = serializer includes role (the confounder).
const BASE_BEHAVIOR: Record<string, string> = {
  B0: `{ revokeEnforced: true, revokeFieldCorrect: true, serializerIncludesRole: false }`,
  B1: `{ revokeEnforced: true, revokeFieldCorrect: true, serializerIncludesRole: true }`,
};

function git(repo: string, args: string[]): string {
  return execFileSync("git", args, { cwd: repo, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] })
    .toString()
    .trim();
}

function initIdentity(repo: string): void {
  git(repo, ["config", "user.name", "M2-A Provenance"]);
  git(repo, ["config", "user.email", "m2-a-provenance@local.invalid"]);
}

/** Stub base application: secure-by-default, denies /profile unconditionally. */
